"""Build paper/results_tables.tex from evaluate.py outputs. Numbers are copied, never typed.

  python scripts/make_paper_tables.py --results results --out paper/results_tables.tex
  python scripts/make_paper_tables.py --pending --out paper/results_tables.tex   # before real runs

Refuses rows from the mock backend unless --allow-synthetic is given; then every table caption is
stamped SYNTHETIC so a mock table can never pass for a result.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

PRIMARY_SET = "medqa_onc+medmcqa_onc"
MAIN_ROWS = [("cot", "CoT (greedy)", 1), ("sc@1", "SC@1", 1), ("sc@5", "SC@5", 5), ("sc@9", "SC@9", 9),
             ("sc@15", "SC@15", 15), ("board_roles.final", "Specialist board", 9),
             ("board_generic.final", "Generic board", 9)]

PENDING = r"""% AUTO-GENERATED by scripts/make_paper_tables.py --pending. No real results exist yet.
\begin{table}[t]
\centering\small
\caption{Main results on the primary oncology set (seed 0). \textbf{PENDING: no real model output yet.}}
\label{tab:main}
\begin{tabular}{lrcc}
\toprule
Method & Calls & Acc. (95\% CI) & $\Delta$ vs SC@9 \\
\midrule
CoT (greedy) & 1 & -- & -- \\
SC@9 & 9 & -- & -- \\
Specialist board & 9 & -- & -- \\
Generic board & 9 & -- & -- \\
\bottomrule
\end{tabular}
\end{table}

\begin{table*}[t]
\centering\small
\caption{Pre-specified paired comparisons. \textbf{PENDING: no real model output yet.}}
\label{tab:comparisons}
\begin{tabular}{llrrrr}
\toprule
Role & Comparison & $\Delta$ (pp) & 95\% CI & $p_{\mathrm{Holm}}$ & MDE (pp) \\
\midrule
Primary & Specialist board vs SC@9 & -- & -- & -- & -- \\
Secondary & Specialist vs generic board & -- & -- & -- & -- \\
Secondary & Round-2 vote vs round-1 vote & -- & -- & -- & -- \\
Secondary & Specialist board vs CoT & -- & -- & -- & -- \\
\bottomrule
\end{tabular}
\end{table*}
"""


def fmt_pct(x):
    return f"{100 * x:.1f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--out", default="paper/results_tables.tex")
    ap.add_argument("--dataset", default=PRIMARY_SET, help="falls back to medqa_onc if the pooled set is absent")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--pending", action="store_true")
    ap.add_argument("--allow-synthetic", action="store_true")
    args = ap.parse_args()
    out = Path(args.out)
    if args.pending:
        out.write_text(PENDING)
        print(f"wrote PENDING tables to {out}")
        return
    res = pd.read_csv(Path(args.results) / "results.csv")
    comp = pd.read_csv(Path(args.results) / "comparisons.csv")
    synthetic = (res["model"] == "mock").any()
    if synthetic and not args.allow_synthetic:
        raise SystemExit("results come from the mock backend; refusing to build paper tables (use --allow-synthetic for a format check)")
    stamp = r" \textbf{SYNTHETIC (mock backend) --- not results.}" if synthetic else ""
    ds = args.dataset if args.dataset in set(res["dataset"]) else "medqa_onc"
    r = res[(res.dataset == ds) & (res.seed == args.seed)].set_index("variant")
    c = comp[(comp.dataset == ds) & (comp.seed == args.seed)]
    ds_tex = ds.replace("_", "\\_")      # no backslash inside f-string braces (Python < 3.12)
    lines = [f"% AUTO-GENERATED by scripts/make_paper_tables.py from {args.results}/ (dataset={ds}, seed={args.seed})",
             r"\begin{table}[t]", r"\centering\small",
             rf"\caption{{Accuracy on {ds_tex} (seed {args.seed}, n={int(r['n'].iloc[0])}); 95\% item-bootstrap CIs; $\Delta$ = accuracy minus SC@9 (points).{stamp}}}",
             r"\label{tab:main}", r"\begin{tabular}{lrccc}", r"\toprule",
             r"Method & Calls & Accuracy (95\% CI) & $\Delta$ vs SC@9 & Parse fail \\", r"\midrule"]
    sc9 = r.loc["sc@9", "accuracy"] if "sc@9" in r.index else None
    for key, label, calls in MAIN_ROWS:
        if key not in r.index:
            continue
        row = r.loc[key]
        delta = f"{100 * (row.accuracy - sc9):+.1f}" if sc9 is not None and key != "sc@9" else "--"
        lines.append(f"{label} & {calls} & {fmt_pct(row.accuracy)} ({fmt_pct(row.ci95_lo)}--{fmt_pct(row.ci95_hi)}) & "
                     f"{delta} & {fmt_pct(row.parse_fail_rate)}\\% \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    lines += [r"\begin{table*}[t]", r"\centering\small",
              rf"\caption{{Pre-specified paired comparisons (exact McNemar; Holm within the secondary family; MDE = smallest difference detectable with 80\% power).{stamp}}}",
              r"\label{tab:comparisons}", r"\begin{tabular}{llrrrr}", r"\toprule",
              r"Role & Comparison & $\Delta$ (pp) & 95\% CI & $p_{\mathrm{Holm}}$ & MDE \\", r"\midrule"]
    for _, x in c.iterrows():
        name = f"{x.a} vs {x.b}".replace("_", r"\_").replace("@", "@")
        mde = "--" if pd.isna(x.mde80_pp) else f"{x.mde80_pp:.1f}"
        lines.append(f"{x.role} & {name} & {x.diff_pp:+.1f} & [{x.diff_ci95_lo_pp:.1f}, {x.diff_ci95_hi_pp:.1f}] & "
                     f"{x.p_holm:.3f} & {mde} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({'SYNTHETIC' if synthetic else 'real'})")


if __name__ == "__main__":
    main()
